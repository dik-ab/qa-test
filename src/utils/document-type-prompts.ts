/**
 * ドキュメントタイプに応じたプロンプトを取得
 * @param documentType ドキュメントタイプ
 * @param customPrompt カスタムプロンプト（オプション）
 * @returns 使用するプロンプト
 */
export function getPromptForDocumentType(
  documentType: DocumentType,
  customPrompt?: string
): string {
  // カスタムプロンプトが指定されている場合はそれを優先
  if (customPrompt) {
    return customPrompt;
  }
  
  // ドキュメントタイプに応じたプロンプトを返す
  return DOCUMENT_TYPE_PROMPTS[documentType];
}